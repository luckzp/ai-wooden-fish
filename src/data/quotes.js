/**
 * 从短句池中随机取一句（可避免连续重复）
 * @param {string} [current] - 当前句，若传则尽量不返回同一句
 * @returns {string}
 */
export function pickRandomQuote(current = '') {
  const list = quotes.filter((q) => q !== current)
  const pool = list.length > 0 ? list : quotes
  return pool[Math.floor(Math.random() * pool.length)]
}
